from __future__ import annotations

import sys
import unittest
from pathlib import Path
from tempfile import TemporaryDirectory

from typer.testing import CliRunner

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from tasc_cli.app import app


class CliTests(unittest.TestCase):
    def setUp(self) -> None:
        self.runner = CliRunner()

    def test_cli_starts_successfully(self) -> None:
        result = self.runner.invoke(app)

        self.assertEqual(result.exit_code, 0)

    def test_help_works(self) -> None:
        result = self.runner.invoke(app, ["--help"])

        self.assertEqual(result.exit_code, 0)

    def test_commands_exist(self) -> None:
        result = self.runner.invoke(app, ["--help"])

        self.assertIn("init", result.output)
        self.assertIn("validate", result.output)
        self.assertIn("bootstrap", result.output)
        self.assertIn("doctor", result.output)

    def test_init_command_creates_workspace(self) -> None:
        with TemporaryDirectory() as temp_dir:
            workspace = Path(temp_dir) / "my-company"
            result = self.runner.invoke(app, ["init", str(workspace)])

            self.assertEqual(result.exit_code, 0)
            self.assertTrue(workspace.is_dir())
            self.assertTrue((workspace / "config" / "core.yaml").is_file())
            self.assertTrue((workspace / "projects").is_dir())
            self.assertTrue((workspace / "agents").is_dir())
            self.assertTrue((workspace / "logs").is_dir())
            self.assertTrue((workspace / "README.md").is_file())
            self.assertEqual(
                (workspace / "workspace.yaml").read_text(encoding="utf-8"),
                "apiVersion: tasc.io/v1alpha1\n"
                "kind: Workspace\n"
                "\n"
                "metadata:\n"
                f"  name: {workspace}\n",
            )
            self.assertEqual(
                (workspace / "README.md").read_text(encoding="utf-8"),
                f"# {workspace}\n\nGenerated by TASC Builder.\n",
            )
            self.assertEqual(
                {path.relative_to(workspace) for path in workspace.rglob("*")},
                {
                    Path("agents"),
                    Path("config"),
                    Path("config/core.yaml"),
                    Path("logs"),
                    Path("projects"),
                    Path("README.md"),
                    Path("workspace.yaml"),
                },
            )

    def test_init_command_rejects_existing_workspace_without_force(self) -> None:
        with TemporaryDirectory() as temp_dir:
            workspace = Path(temp_dir) / "my-company"
            workspace.mkdir()

            result = self.runner.invoke(app, ["init", str(workspace)])

            self.assertNotEqual(result.exit_code, 0)
            self.assertIn("already exists", result.output)

    def test_init_command_overwrites_existing_workspace_with_force(self) -> None:
        with TemporaryDirectory() as temp_dir:
            workspace = Path(temp_dir) / "my-company"
            workspace.mkdir()
            (workspace / "existing.txt").write_text("old", encoding="utf-8")

            result = self.runner.invoke(app, ["init", str(workspace), "--force"])

            self.assertEqual(result.exit_code, 0)
            self.assertFalse((workspace / "existing.txt").exists())
            self.assertTrue((workspace / "config" / "core.yaml").is_file())

    def test_validate_command(self) -> None:
        result = self.runner.invoke(app, ["validate"])

        self.assertEqual(result.exit_code, 0)
        self.assertEqual(
            result.output,
            "Configuration validation is not yet implemented.\n",
        )

    def test_bootstrap_command(self) -> None:
        result = self.runner.invoke(app, ["bootstrap"])

        self.assertEqual(result.exit_code, 0)
        self.assertEqual(result.output, "Bootstrap is not yet implemented.\n")

    def test_doctor_command(self) -> None:
        result = self.runner.invoke(app, ["doctor"])

        self.assertEqual(result.exit_code, 0)
        self.assertEqual(
            result.output,
            "Environment diagnostics are not yet implemented.\n",
        )


if __name__ == "__main__":
    unittest.main()
